#pragma once

#include "CoreMinimal.h"

/**
 * 채팅 금지어 필터. 순수 함수만 둔다.
 *
 * 컴포넌트가 아니라 네임스페이스인 이유는 TDEnhance 와 같다(D77) — 입력만으로
 * 결과가 정해지므로 월드도 액터도 필요 없고, 테스트에서 문자열만 넣어 확인할 수 있다.
 *
 * ── 어디까지 잡는가 ──
 * 공백과 특수문자를 걷어낸 뒤 검사한다. 그래서 이런 것들이 잡힌다.
 *
 *   "욕 설"      공백 제거
 *   "욕!설"      특수문자 제거
 *   "욕...설"    마찬가지
 *
 * 글자를 끼워 넣는 우회("욕이설")는 잡지 못한다. 끼운 글자를 지우려면 어떤 글자가
 * 군더더기인지 알아야 하는데, 그 판단은 정상 단어까지 망가뜨린다.
 *
 * 초성(ㅅㅂ)을 자동으로 변환하지도 않는다. 정상 단어의 초성이 금지어와 겹치는
 * 경우가 생각보다 많아 오탐이 늘기 때문이다. 다만 **자모 자체는 지우지 않으므로**,
 * 필요하면 DT_BannedWord 에 "ㅅㅂ" 을 한 줄 넣어 직접 잡을 수 있다.
 *
 * 한국어 욕설은 우회가 끝이 없어 완전한 차단이 애초에 불가능하다. 어디서 멈출지의
 * 문제이고, 여기서는 "쉬운 우회만 막고 오탐은 만들지 않는다" 로 정했다.
 */
namespace TDChatFilter
{
	/**
	 * 금지어를 `*` 로 가린 문자열을 돌려준다. 걸린 것이 없으면 원본 그대로다.
	 *
	 * 가리는 자리는 **원본 기준**이다. "시 발" 이 걸리면 가운데 공백까지 포함해
	 * 세 글자가 `***` 가 된다 — 정규화한 문자열에서 찾은 구간을 원본 위치로
	 * 되돌려 계산하기 때문이다.
	 *
	 * @param Message      검사할 원본 메시지
	 * @param BannedWords  금지어 목록. 빈 항목은 무시한다
	 * @param bOutMasked   하나라도 걸렸으면 true. 로그나 통계에 쓸 수 있다
	 */
	FString Mask(const FString& Message, const TArray<FString>& BannedWords, bool& bOutMasked);

	/**
	 * 검사용으로 문자열을 정규화한다. 위 Mask 가 내부에서 쓴다.
	 *
	 * 소문자로 낮추고, 글자·숫자가 아닌 것을 버린다. 남기는 것은 영문·숫자·한글
	 * (완성형과 호환 자모)이다.
	 *
	 * @param OutSourceIndex  정규화 결과의 i 번째 문자가 원본 몇 번째에서 왔는지.
	 *                        마스킹 구간을 원본 좌표로 되돌릴 때 필요하다.
	 */
	FString Normalize(const FString& Message, TArray<int32>& OutSourceIndex);
}
